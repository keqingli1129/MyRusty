// Code that follows along with docs/panic.txt (Rust Curious, lesson 3: Panic!).
//
// Run it with:  cargo run --bin panic -- <which>
// where <which> picks a panic to trigger: overflow, divide, index, unwrap, explicit, assert.
// With no argument it only runs the parts that don't panic.

// `use` brings a name into scope so we can write `black_box` instead of `std::hint::black_box`.
// black_box hides a value from the compiler, so it can't spot a guaranteed panic at compile
// time and refuse to build. Real code doesn't need this; it's only here to make the demos run.
use std::hint::black_box;

// ---------------------------------------------------------------------------
// Local cargo project setup
// ---------------------------------------------------------------------------
//
// The video starts with `cargo new fact`, which creates:
//     fact/Cargo.toml    the project manifest: name, version, edition, dependencies
//     fact/src/main.rs   a Hello World main function, ready to build
//
//     cargo build   compiles to target/debug/<project name> (fact.exe on Windows)
//     cargo run     builds and runs in one step
//     cargo test    builds the test runner and runs every #[test] function
//
// This repo is already a cargo project, so this lesson lives in src/bin/panic.rs instead.
// Cargo builds every file in src/bin/ as its own program, named after the file.

// ---------------------------------------------------------------------------
// Hello World has a crashing bug
// ---------------------------------------------------------------------------

fn hello_world() {
    // If writing to stdout fails, println! panics with
    // "failed printing to stdout: Broken pipe (os error 32)".
    // You can see it by piping the output into a program that closes its input, e.g.
    //     ./target/debug/panic | echo
    // Programs that may run without a terminal should use a logging framework instead.
    println!("Hello, world!");
}

// ---------------------------------------------------------------------------
// Solving the factorial exercise
// ---------------------------------------------------------------------------

// The recursive version from lesson 2 has been replaced by a loop and a mutable variable.
fn factorial(n: u64) -> u64 {
    let mut x = 1; // running product; starting at 1 makes 0! and 1! come out as 1
    for i in 2..=n {
        // multiply by 2, 3, ..., n (multiplying by 1 wouldn't change anything)
        x *= i; // in a debug build this panics if the product doesn't fit in a u64
    }
    x // the final expression is the return value
}

// Prints factorial(n) for every n from 0 up to and including `max`.
fn factorial_table(max: u64) {
    for n in 0..=max {
        // print one line per value of n
        println!("factorial({}) = {}", n, factorial(n));
    }
}

// ---------------------------------------------------------------------------
// Making it panic: things that can cause a panic
// ---------------------------------------------------------------------------

// 1. Integer overflow, generated by the compiler.
fn integer_overflow() {
    // 20! is the largest factorial that fits in a u64, so 21! overflows and panics with
    // "attempt to multiply with overflow". Only debug builds check for this:
    // `cargo run --release` turns the checks off, so the value silently wraps around instead.
    factorial_table(25);
}

// 2. Integer division by zero, generated by the compiler.
fn divide_by_zero() {
    let total: u32 = 100; // the number to divide
    let count: u32 = black_box(0); // zero, hidden from the compiler (see the `use` at the top)
    // Panics with "attempt to divide by zero", in debug AND release builds.
    println!("average is {}", total / count);
}

// 3. Out-of-bounds array access, generated by the compiler.
fn index_out_of_bounds() {
    let values = [10, 20, 30]; // an array of 3 items, so the valid indexes are 0, 1 and 2
    let i: usize = black_box(5); // an index past the end, hidden from the compiler
    // Rust checks every index. Instead of reading whatever memory is past the end, like C
    // would, this panics with "index out of bounds: the len is 3 but the index is 5".
    println!("values[{}] is {}", i, values[i]);
}

// 4. unwrap, from library code.
fn unwrap_error() {
    // parse() tries to turn a string into a number. It returns a Result, which is either
    // Ok(number) or Err(error), so the caller has to deal with failure.
    let parsed: Result<u32, _> = "not a number".parse();
    // unwrap() means "give me the number, and panic if it's an error". It's the easy way to
    // get at the data in toy programs. Panics with
    // "called `Result::unwrap()` on an `Err` value: ParseIntError { kind: InvalidDigit }".
    let n = parsed.unwrap();
    // Never reached.
    println!("parsed {}", n);
}

// 5. An explicit panic, using a macro.
fn explicit_panic() {
    let code = 42; // a value to include in the message
    // panic! stops the thread right away. It takes a format string, just like println!.
    panic!("something went badly wrong, code {}", code);
}

// 6. A failed assertion, also a macro.
fn failed_assertion() {
    let x = black_box(5); // the value we're checking
    // assert! panics if the condition is false; the message after the comma is optional.
    // assert_eq! (used in the unit tests) compares two values and panics if they differ.
    assert!(x < 3, "x should be less than 3, but it was {}", x);
    // Never reached.
    println!("assertion passed");
}

// ---------------------------------------------------------------------------
// Panic does what? Unwind vs Abort
// ---------------------------------------------------------------------------
//
// Whatever caused the panic (the compiler, a library, or a macro), there are two options:
//
//   unwind (the default): the panicking thread stops and cleans up as it goes. Other
//                         threads keep running. If main's thread panics, the program exits.
//   abort:                the whole process stops immediately, every thread at once.
//
// You choose in Cargo.toml, separately for each build profile:
//
//     [profile.dev]
//     panic = "abort"
//
//     [profile.release]
//     panic = "abort"
//
// Threads are needed to see the difference. src/bin/factd.rs is the network service from
// the video for that: cargo run --bin factd

// ---------------------------------------------------------------------------
// main: choose a panic from the command line
// ---------------------------------------------------------------------------

fn main() {
    hello_world(); // the Hello World with the crashing bug

    // std::env::args() lists the command-line arguments; item 0 is the program itself,
    // so nth(1) is the first real argument. It returns an Option: Some(text) or None.
    let which = std::env::args().nth(1);

    // as_deref() turns Option<String> into Option<&str>, so we can match string literals.
    match which.as_deref() {
        Some("overflow") => integer_overflow(), // 1. integer overflow
        Some("divide") => divide_by_zero(), // 2. division by zero
        Some("index") => index_out_of_bounds(), // 3. out-of-bounds array access
        Some("unwrap") => unwrap_error(), // 4. unwrap on an error
        Some("explicit") => explicit_panic(), // 5. panic! macro
        Some("assert") => failed_assertion(), // 6. failed assertion
        Some(other) => println!("unknown option: {}", other), // anything else
        None => {
            // No argument: run the exercise up to 20, which doesn't panic,
            factorial_table(20);
            // and list the options.
            println!("pick a panic: cargo run --bin panic -- overflow|divide|index|unwrap|explicit|assert");
        }
    }
}

// ---------------------------------------------------------------------------
// Unit tests, including tests that check a function panics
// ---------------------------------------------------------------------------

// A normal test: passes if it returns without panicking.
#[test]
fn test_factorial() {
    assert_eq!(factorial(0), 1); // 0! = 1
    assert_eq!(factorial(1), 1); // 1! = 1
    assert_eq!(factorial(5), 120); // 1*2*3*4*5
    assert_eq!(factorial(20), 2_432_902_008_176_640_000); // largest that fits in a u64
}

// #[should_panic] reverses the rule: the test passes only if the function panics.
// `expected` also requires the panic message to contain this text, so the test can't pass
// because of some other, unrelated panic.
// (Running `cargo test --release` would fail this one: release builds don't check overflow.)
#[test]
#[should_panic(expected = "attempt to multiply with overflow")]
fn test_factorial_overflow_panics() {
    factorial(21); // 21! doesn't fit in a u64
}

// Division by zero panics in every build.
#[test]
#[should_panic(expected = "attempt to divide by zero")]
fn test_divide_by_zero_panics() {
    divide_by_zero(); // should panic before it prints anything
}

// Indexing past the end of an array panics.
#[test]
#[should_panic(expected = "index out of bounds")]
fn test_index_out_of_bounds_panics() {
    index_out_of_bounds(); // index 5 into a 3-item array
}

// unwrap on an Err panics.
#[test]
#[should_panic(expected = "called `Result::unwrap()` on an `Err` value")]
fn test_unwrap_error_panics() {
    unwrap_error(); // parsing "not a number" fails
}

// panic! panics with the message we gave it.
#[test]
#[should_panic(expected = "code 42")]
fn test_explicit_panic() {
    explicit_panic(); // the formatted message contains "code 42"
}

// assert! panics with its custom message when the condition is false.
#[test]
#[should_panic(expected = "x should be less than 3")]
fn test_failed_assertion_panics() {
    failed_assertion(); // 5 < 3 is false
}
